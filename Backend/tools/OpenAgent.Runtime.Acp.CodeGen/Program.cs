using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;
using System.Text.RegularExpressions;

namespace OpenAgent.Runtime.Acp.CodeGen;

internal static class Program
{
    private const string Header = "// <auto-generated />\n#nullable enable\n";
    private static readonly SortedDictionary<string, JsonObject> Schemas = new(StringComparer.Ordinal);
    private static readonly SortedSet<string> ContextTypes = new(StringComparer.Ordinal);
    private static readonly Dictionary<string, string> Native = new(StringComparer.Ordinal);
    private static readonly Dictionary<string, string> Files = new(StringComparer.Ordinal);
    /// <summary>Untagged union variants whose upstream documentation defines their implicit wire tag.</summary>
    private static readonly Dictionary<string, string> DefaultVariants = new(StringComparer.Ordinal) { ["AuthMethod"] = "agent" };

    /// <summary>
    /// PROTOCOL.md §5: a missing AuthMethod type means the agent method. Pin the untagged
    /// agent candidate to its tag so any other discriminator value is rejected instead of
    /// silently degrading to the agent variant; the pinned candidate also feeds the emitted
    /// branch definition, keeping the runtime schema self-describing.
    /// </summary>
    private static void PinDefaultVariants()
    {
        foreach ((string name, string tag) in DefaultVariants)
        {
            JsonObject definition = Schemas[name];
            JsonArray alternatives = (JsonArray?)definition["oneOf"] ?? (JsonArray)definition["anyOf"]!;
            string? discriminator = alternatives.OfType<JsonObject>()
                .Select(item => item["properties"]).OfType<JsonObject>()
                .SelectMany(fields => fields).Where(pair => pair.Value is JsonObject field && field["const"] is JsonValue)
                .Select(pair => pair.Key).FirstOrDefault();
            if (discriminator is null) throw new InvalidDataException("Default variant without a tagged sibling: " + name);
            foreach (JsonObject candidate in alternatives.OfType<JsonObject>())
            {
                if (candidate["properties"] is not null || candidate["title"]?.GetValue<string>() != tag) continue;
                candidate["properties"] = new JsonObject { [discriminator] = new JsonObject { ["const"] = tag } };
            }
        }
    }

    private static int Main(string[] args)
    {
        try { return Generate(args); }
        catch (Exception exception)
        {
            Console.Error.WriteLine($"CodeGen failed: {exception.GetType().Name}: {exception.Message}");
            return 1;
        }
    }

    private static int Generate(string[] args)
    {
        if (args.Length is < 1 or > 2 || args.Length == 2 && args[1] != "--check")
        {
            Console.Error.WriteLine("Usage: CodeGen <repository-root> [--check]");
            return 2;
        }
        string root = Path.GetFullPath(args[0]);
        string docs = Path.Combine(root, "docs/integrations/acp-dotnet-sdk");
        JsonObject source = JsonNode.Parse(File.ReadAllText(Path.Combine(docs, "sources.json")))!.AsObject();
        JsonObject baseline = source["protocol_baseline"]!.AsObject();
        JsonObject schema = ReadLocked(docs, "schema/v1/schema.json", baseline["schema_sha256"]!.GetValue<string>());
        JsonObject meta = ReadLocked(docs, "schema/v1/meta.json", baseline["meta_sha256"]!.GetValue<string>());
        JsonObject licenseLock = JsonNode.Parse(File.ReadAllText(Path.Combine(docs, "schema/lock.json")))!.AsObject();
        ReadHash(Path.Combine(docs, "schema/v1/LICENSE"), licenseLock["license_sha256"]!.GetValue<string>());
        if (meta["version"]!.GetValue<int>() != 1 || baseline["protocol_version"]!.GetValue<int>() != 1 ||
            baseline["commit"]!.GetValue<string>() != licenseLock["commit"]!.GetValue<string>() ||
            baseline["schema_sha256"]!.GetValue<string>() != licenseLock["schema_sha256"]!.GetValue<string>() ||
            baseline["meta_sha256"]!.GetValue<string>() != licenseLock["meta_sha256"]!.GetValue<string>() ||
            baseline["license_sha256"]!.GetValue<string>() != licenseLock["license_sha256"]!.GetValue<string>() ||
            baseline["license"]!.GetValue<string>() != "Apache-2.0" || licenseLock["license"]!.GetValue<string>() != "Apache-2.0" ||
            licenseLock["schema_path"]!.GetValue<string>() != "v1/schema.json" ||
            licenseLock["meta_path"]!.GetValue<string>() != "v1/meta.json" ||
            licenseLock["license_path"]!.GetValue<string>() != "v1/LICENSE")
            throw new InvalidDataException("Protocol lock mismatch.");
        foreach ((string name, JsonNode? value) in schema["$defs"]!.AsObject()) Schemas.Add(name, value!.AsObject());
        string[] originals = Schemas.Keys.ToArray();
        if (originals.Length != baseline["definition_count"]!.GetValue<int>()) throw new InvalidDataException("Definition count mismatch.");
        PinDefaultVariants();
        foreach (string name in originals)
        {
            string? native = Scalar(Schemas[name]);
            if (name == "RequestId") native = "RpcId";
            if (native is not null) Native.Add(name, native);
        }
        // Type discovery may introduce named inline unions and flattened variant DTOs.
        HashSet<string> emitted = new(StringComparer.Ordinal);
        while (Schemas.Keys.FirstOrDefault(name => !emitted.Contains(name)) is { } name)
        {
            emitted.Add(name);
            Emit(name, Schemas[name]);
        }
        EmitCatalog(originals, baseline, meta);
        StringBuilder context = new(Header + "using System.Text.Json;\nusing System.Text.Json.Serialization;\nnamespace OpenAgent.Runtime.Acp.Protocol;\n\n[JsonSourceGenerationOptions(GenerationMode = JsonSourceGenerationMode.Metadata)]\n");
        foreach (string type in ContextTypes) context.AppendLine($"[JsonSerializable(typeof({type}))]");
        context.AppendLine("public partial class AcpJsonContext : JsonSerializerContext;");
        Files.Add("AcpJsonContext.g.cs", context.ToString());
        JsonObject definitions = new();
        foreach ((string name, JsonObject value) in Schemas) definitions[name] = value.DeepClone();
        Files.Add("ProtocolSchema.g.json", new JsonObject { ["$defs"] = definitions }.ToJsonString() + "\n");
        string output = Path.Combine(root, "Backend/src/OpenAgent.Runtime.Acp/Protocol/Generated");
        if (args.Length == 2)
        {
            string[] existing = Directory.GetFiles(output).Select(Path.GetFileName).Order(StringComparer.Ordinal).ToArray()!;
            if (!existing.SequenceEqual(Files.Keys.Order(StringComparer.Ordinal))) throw new InvalidDataException("Generated file list drift.");
            foreach ((string path, string contents) in Files)
                if (!File.ReadAllBytes(Path.Combine(output, path)).AsSpan().SequenceEqual(Encoding.UTF8.GetBytes(contents.Replace("\r\n", "\n"))))
                    throw new InvalidDataException("Generated file drift: " + path);
            Console.WriteLine($"Verified {Files.Count} generated files without writing.");
            return 0;
        }
        Directory.CreateDirectory(output);
        foreach (string path in Directory.GetFiles(output))
            if (!Files.ContainsKey(Path.GetFileName(path)))
            {
                if (path.EndsWith(".g.cs", StringComparison.Ordinal) && File.ReadAllText(path).StartsWith(Header, StringComparison.Ordinal)) File.Delete(path);
                else throw new InvalidDataException($"Unexpected generated file: {Path.GetFileName(path)}");
            }
        foreach ((string path, string contents) in Files.OrderBy(pair => pair.Key, StringComparer.Ordinal))
            File.WriteAllText(Path.Combine(output, path), contents.Replace("\r\n", "\n"), new UTF8Encoding(false));
        Console.WriteLine($"Generated {originals.Length} definitions, {baseline["methods"]!.AsArray().Count} methods, {baseline["session_update_variants"]!.AsArray().Count} updates; {Files.Count} files.");
        return 0;
    }

    private static JsonObject ReadLocked(string docs, string path, string hash)
    {
        string full = Path.Combine(docs, path);
        ReadHash(full, hash);
        return JsonNode.Parse(File.ReadAllText(full))!.AsObject();
    }

    private static void ReadHash(string path, string expected)
    {
        string actual = Convert.ToHexStringLower(SHA256.HashData(File.ReadAllBytes(path)));
        if (actual != expected) throw new InvalidDataException($"Hash mismatch: {Path.GetFileName(path)}");
    }

    private static string Quote(string text) => JsonSerializer.Serialize(text);
    private static string Pascal(string name) => string.Concat(Regex.Split(name, "[^a-zA-Z0-9]+").Where(p => p.Length > 0).Select(p => char.ToUpperInvariant(p[0]) + p[1..]));
    private static string Property(string wire, string owner)
    {
        string name = wire == "_meta" ? "Meta" : Pascal(wire);
        return name == owner || name is "Json" or "SchemaName" ? name + "Value" : name;
    }
    private static string Parameter(string wire) => "@" + (wire == "_meta" ? "meta" : wire);

    private static string? Scalar(JsonObject schema)
    {
        if (schema["type"] is JsonValue type)
            return type.GetValue<string>() switch
            {
                "string" => "string", "boolean" => "bool", "number" => "double",
                "integer" => schema["format"]?.GetValue<string>() switch
                {
                    "uint16" => "ushort", "uint32" => "uint", "uint64" => "ulong", "int32" => "int", _ => "long"
                },
                _ => null
            };
        if ((schema["oneOf"] ?? schema["anyOf"]) is JsonArray alternatives && alternatives.All(item => item is JsonObject obj && Scalar(obj) is not null))
        {
            string[] types = alternatives.Select(item => Scalar(item!.AsObject())!).Distinct().ToArray();
            return types.Length == 1 ? types[0] : null;
        }
        return null;
    }

    private static JsonObject Expand(JsonObject value)
    {
        JsonObject result = new();
        if (value["$ref"] is JsonValue reference) Merge(result, Expand(Schemas[reference.GetValue<string>().Split('/')[^1]]));
        if (value["allOf"] is JsonArray all) foreach (JsonNode? item in all) Merge(result, Expand(item!.AsObject()));
        Merge(result, value);
        result.Remove("$ref"); result.Remove("allOf");
        return result;
    }

    private static void Merge(JsonObject target, JsonObject source)
    {
        foreach ((string key, JsonNode? value) in source)
        {
            if (key == "properties" && target[key] is JsonObject properties)
            {
                foreach ((string name, JsonNode? field) in value!.AsObject()) properties[name] = field?.DeepClone();
            }
            else if (key == "required" && target[key] is JsonArray required)
            {
                foreach (string name in value!.AsArray().Select(item => item!.GetValue<string>()))
                    if (!required.Any(item => item!.GetValue<string>() == name)) required.Add(name);
            }
            else target[key] = value?.DeepClone();
        }
    }

    private static string TypeFor(JsonObject value, string suggestion)
    {
        string result;
        if (value["$ref"] is JsonValue reference)
        {
            string name = reference.GetValue<string>().Split('/')[^1];
            result = Native.GetValueOrDefault(name, name);
        }
        else if (value["allOf"] is JsonArray all && all.Count == 1 && !value.ContainsKey("properties")) result = TypeFor(all[0]!.AsObject(), suggestion);
        else if (value["anyOf"] is JsonArray any && any.Count == 2 && any.Count(n => n?["type"]?.ToJsonString() == "\"null\"") == 1)
            result = TypeFor(any.Single(n => n?["type"]?.ToJsonString() != "\"null\"")!.AsObject(), suggestion);
        else
        {
            JsonObject nonnull = (JsonObject)value.DeepClone();
            if (nonnull["type"] is JsonArray types) nonnull["type"] = types.First(item => item!.GetValue<string>() != "null")!.DeepClone();
            result = Scalar(nonnull) ?? "";
            if (result.Length == 0)
            {
                string? type = nonnull["type"]?.GetValue<string>();
                if (type == "array") result = TypeFor(nonnull["items"]!.AsObject(), suggestion + "Item") + "[]";
                else if (type == "object" && nonnull["additionalProperties"] is JsonObject map)
                    result = "Dictionary<string, " + TypeFor(map, suggestion + "Value") + ">";
                else if (type == "object" && !nonnull.ContainsKey("properties")) result = "JsonElement";
                else if (nonnull.ContainsKey("anyOf") || nonnull.ContainsKey("oneOf") || nonnull.ContainsKey("properties"))
                {
                    if (!Schemas.ContainsKey(suggestion)) Schemas.Add(suggestion, nonnull);
                    result = suggestion;
                }
                else result = "JsonElement";
            }
        }
        ContextTypes.Add(result);
        return result;
    }

    private static void Emit(string name, JsonObject original)
    {
        if (Native.TryGetValue(name, out string? native))
        {
            ContextTypes.Add(native);
            JsonArray? values = (original["oneOf"] ?? original["anyOf"]) as JsonArray;
            if (values is null || name == "RequestId") return;
            StringBuilder constants = new(Header + "namespace OpenAgent.Runtime.Acp.Protocol;\n\npublic static class " + name + "\n{\n");
            foreach (JsonObject item in values.OfType<JsonObject>().Where(item => item.ContainsKey("const")))
            {
                string title = item["title"]?.GetValue<string>() ?? Pascal(item["const"]!.GetValue<string>());
                constants.AppendLine($"    public const {native} {Pascal(title)} = {item["const"]!.ToJsonString()};");
            }
            constants.AppendLine("}"); Files.Add(name + ".g.cs", constants.ToString()); return;
        }
        ContextTypes.Add(name);
        JsonObject schema = Expand(original);
        JsonArray? alternatives = (schema["oneOf"] ?? schema["anyOf"]) as JsonArray;
        StringBuilder code = new(Header + "using System.Text.Json;\nusing System.Text.Json.Serialization;\nusing OpenAgent.Runtime.Acp.Protocol.Serialization;\nnamespace OpenAgent.Runtime.Acp.Protocol;\n\n");
        code.AppendLine($"[JsonConverter(typeof({name}Converter))]\npublic sealed class {name} : AcpModel\n{{");
        code.AppendLine($"    internal {name}(JsonElement value, bool validated) : base({Quote(name)}, value, validated) {{ }}");
        if (alternatives is not null)
        {
            JsonObject common = (JsonObject)schema.DeepClone(); common.Remove("oneOf"); common.Remove("anyOf"); common.Remove("discriminator");
            List<string> labels = [];
            for (int index = 0; index < alternatives.Count; index++)
            {
                JsonObject branch = alternatives[index]!.AsObject();
                JsonObject expanded = Expand(branch);
                string? tag = expanded["properties"]?.AsObject().FirstOrDefault(pair => pair.Value?["const"] is JsonValue).Value?["const"]?.GetValue<string>();
                string label = tag is not null ? Pascal(tag) : Pascal(branch["title"]?.GetValue<string>() ?? (branch["allOf"]?[0]?["$ref"]?.GetValue<string>().Split('/')[^1]) ?? "Variant" + (index + 1));
                if (label is "String" or "Integer" or "Number" or "Boolean" or "StringArray" or "Null") label += "Value";
                if (labels.Contains(label)) label += index + 1;
                labels.Add(label);
                string branchName = name + label;
                if (Schemas.ContainsKey(branchName)) branchName += "Variant";
                JsonObject combined = Expand(new JsonObject { ["allOf"] = new JsonArray(common.DeepClone(), branch.DeepClone()) });
                // A branch may itself contain another union (for example elicitation scope).
                if (!Schemas.ContainsKey(branchName)) Schemas.Add(branchName, combined);
                code.AppendLine($"    public {name}({branchName} value) : base({Quote(name)}, (value ?? throw new ArgumentNullException(nameof(value))).Json, false) {{ }}");
                code.AppendLine($"    public {branchName} As{label}() => new(Json, false);");
            }
            EmitGetters(code, name, common);
        }
        else if (schema["type"]?.ToJsonString() == "\"object\"" && schema["properties"] is JsonObject properties)
        {
            HashSet<string> required = schema["required"]?.AsArray().Select(n => n!.GetValue<string>()).ToHashSet(StringComparer.Ordinal) ?? [];
            List<string> parameters = [];
            foreach ((string wire, JsonNode? field) in properties.Where(pair => required.Contains(pair.Key) && pair.Value?["const"] is null).Concat(properties.Where(pair => !required.Contains(pair.Key) && pair.Value?["const"] is null)))
            {
                string type = TypeFor(field!.AsObject(), name + Property(wire, name));
                parameters.Add(required.Contains(wire) ? $"{type} {Parameter(wire)}" : $"Optional<{type}> {Parameter(wire)} = default");
            }
            code.AppendLine($"    public {name}({string.Join(", ", parameters)}) : base({Quote(name)}, Build(writer =>\n    {{\n        writer.WriteStartObject();");
            foreach ((string wire, JsonNode? field) in properties)
            {
                if (field?["const"] is JsonNode constant)
                    code.AppendLine($"        writer.WriteString({Quote(wire)}, {constant.ToJsonString()});");
                else if (required.Contains(wire)) code.AppendLine($"        Write(writer, {Quote(wire)}, {Parameter(wire)});");
                else code.AppendLine($"        WriteOptional(writer, {Quote(wire)}, {Parameter(wire)});");
            }
            code.AppendLine("        writer.WriteEndObject();\n    }), false) { }");
            EmitGetters(code, name, schema);
        }
        else
        {
            string type = TypeForValue(schema, name);
            ContextTypes.Add(type);
            code.AppendLine($"    public {name}({type} value) : base({Quote(name)}, AcpJson.ToElement(value), false) {{ }}\n    public {type} Value => AcpJson.FromElement<{type}>(Json);");
        }
        code.AppendLine("}");
        Files.Add(name + ".g.cs", code.ToString());
        Files.Add(name + "Converter.g.cs", Header + "using OpenAgent.Runtime.Acp.Protocol.Serialization;\nnamespace OpenAgent.Runtime.Acp.Protocol;\n\n" +
            $"internal sealed class {name}Converter() : AcpModelConverter<{name}>({Quote(name)}, static value => new {name}(value, true));\n");
    }

    private static string TypeForValue(JsonObject schema, string name)
    {
        if (schema["type"]?.ToJsonString() == "\"array\"") return TypeFor(schema["items"]!.AsObject(), name + "Item") + "[]";
        return Scalar(schema) ?? "JsonElement";
    }

    private static void EmitGetters(StringBuilder code, string owner, JsonObject schema)
    {
        if (schema["properties"] is not JsonObject properties) return;
        HashSet<string> required = schema["required"]?.AsArray().Select(n => n!.GetValue<string>()).ToHashSet(StringComparer.Ordinal) ?? [];
        foreach ((string wire, JsonNode? field) in properties)
        {
            string type = TypeFor(field!.AsObject(), owner + Property(wire, owner));
            string name = Property(wire, owner);
            code.AppendLine(required.Contains(wire)
                ? $"    public {type} {name} => Get<{type}>({Quote(wire)});"
                : $"    public Optional<{type}> {name} => GetOptional<{type}>({Quote(wire)});");
            if (field?["default"] is JsonNode fallback)
                code.AppendLine($"    public {type} {name}OrDefault => {name}.HasValue ? {name}.Value : AcpJson.FromElement<{type}>(AcpJson.ParseElement({Quote(fallback.ToJsonString())}));");
        }
    }

    private static void EmitCatalog(string[] originals, JsonObject baseline, JsonObject meta)
    {
        JsonArray methods = baseline["methods"]!.AsArray();
        string[] metaMethods = new[] { "agentMethods", "clientMethods", "protocolMethods" }.SelectMany(key => meta[key]!.AsObject().Select(pair => pair.Value!.GetValue<string>())).Order(StringComparer.Ordinal).ToArray();
        if (!metaMethods.SequenceEqual(methods.Select(n => n!["method"]!.GetValue<string>()).Order(StringComparer.Ordinal))) throw new InvalidDataException("Method catalog mismatch.");
        StringBuilder code = new(Header + "using System.Collections.ObjectModel;\nnamespace OpenAgent.Runtime.Acp.Protocol;\n\npublic static class AcpProtocol\n{\n    public const int Version = 1;\n");
        code.AppendLine($"    public const string SourceCommit = {Quote(baseline["commit"]!.GetValue<string>())};");
        code.AppendLine($"    public const string SchemaSha256 = {Quote(baseline["schema_sha256"]!.GetValue<string>())};");
        code.AppendLine("    public static IReadOnlyList<AcpMethodDescriptor> Methods { get; } = Array.AsReadOnly<AcpMethodDescriptor>([");
        foreach (JsonNode? method in methods)
        {
            string wire = method!["method"]!.GetValue<string>();
            string[] declared = method["schema_types"]!.AsArray().Select(n => n!.GetValue<string>()).Order(StringComparer.Ordinal).ToArray();
            string[] actual = originals.Where(name => Schemas[name]["x-method"]?.GetValue<string>() == wire).Order(StringComparer.Ordinal).ToArray();
            if (!declared.SequenceEqual(actual)) throw new InvalidDataException("x-method mismatch: " + wire);
            string expectedSide = method["direction"]!.GetValue<string>() switch { "client_to_agent" => "agent", "agent_to_client" => "client", _ => "protocol" };
            if (actual.Any(name => Schemas[name]["x-side"]!.GetValue<string>() != expectedSide)) throw new InvalidDataException("x-side mismatch: " + wire);
            string request = declared.Single(name => !name.EndsWith("Response", StringComparison.Ordinal));
            string? response = declared.SingleOrDefault(name => name.EndsWith("Response", StringComparison.Ordinal));
            code.AppendLine($"        new({Quote(wire)}, {Quote(method["direction"]!.GetValue<string>())}, {Quote(method["kind"]!.GetValue<string>())}, {Quote(request)}, {(response is null ? "null" : Quote(response))}),");
        }
        code.AppendLine("    ]);\n    public static IReadOnlyList<string> SessionUpdates { get; } = Array.AsReadOnly<string>([");
        string[] updates = Schemas["SessionUpdate"]["oneOf"]!.AsArray().Select(n => n!["properties"]!["sessionUpdate"]!["const"]!.GetValue<string>()).ToArray();
        if (!updates.SequenceEqual(baseline["session_update_variants"]!.AsArray().Select(n => n!.GetValue<string>()))) throw new InvalidDataException("Update variants mismatch.");
        foreach (string update in updates) code.AppendLine("        " + Quote(update) + ",");
        code.AppendLine("    ]);\n    public static IReadOnlyDictionary<string, AcpSchemaDescriptor> Schemas { get; } = new ReadOnlyDictionary<string, AcpSchemaDescriptor>(new Dictionary<string, AcpSchemaDescriptor>(StringComparer.Ordinal)\n    {");
        foreach (string name in originals) code.AppendLine($"        [{Quote(name)}] = new({Quote(name)}, typeof({Native.GetValueOrDefault(name, name)})),");
        code.AppendLine("    });\n}");
        Files.Add("AcpProtocol.g.cs", code.ToString());
    }
}
